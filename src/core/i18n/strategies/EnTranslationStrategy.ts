export class EnTranslationStrategy implements ITranslationStrategy {
  readonly locale = 'en';
  readonly displayName = 'English';

  translate(key: TranslationKey | string): string {
    return DICT[key] ?? key;
  }

  translateRaw(key: string): string {
    return (DICT as Record<string, string>)[key] ?? key;
  }
}
