export class KoTranslationStrategy implements ITranslationStrategy {
  readonly locale = 'ko';
  readonly displayName = '한국어';

  translate(key: TranslationKey | string): string {
    return DICT[key] ?? key;
  }

  translateRaw(key: string): string {
    return (DICT as Record<string, string>)[key] ?? key;
  }
}
